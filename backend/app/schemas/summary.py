"""Pydantic schemas for Privacy-Preserving Summarization Engine & Verification (Phase P6).

Strict Privacy Guarantees:
1. SanitizedDocument contract: Enforces that summarizer receives ONLY verified sanitized text,
   opaque document_id, verification reference, format, and permitted metadata.
   Never receives original document objects, raw text, original PDFs, unredacted candidates,
   or raw coordinates.
2. StructuredSummaryContent: Strict schema for model output requiring summary text, key points,
   important findings, validated dates/figures, and source evidence.
3. SummaryVerificationReport: Multi-tiered verification report covering direct leakage, alias variants,
   PII re-detection, quasi-identifier risk, and source consistency.
4. Safe Masked Reporting: No raw PII strings are ever exposed in issues, logs, or error responses.
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class SummaryState(str, Enum):
    """Lifecycle state of privacy-safe summary."""
    PENDING = "PENDING"
    GENERATING = "GENERATING"
    VERIFYING = "VERIFYING"
    VERIFIED = "VERIFIED"
    SUPPRESSED = "SUPPRESSED"
    FAILED = "FAILED"
    REQUIRES_REVIEW = "REQUIRES_REVIEW"


class SummaryEngine(str, Enum):
    """Engine utilized to generate document summary."""
    SLM = "SLM"
    EXTRACTIVE_FALLBACK = "EXTRACTIVE_FALLBACK"


class QuasiRiskLevel(str, Enum):
    """Statistical re-identification risk level for quasi-identifier co-occurrences."""
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"


class SanitizedDocument(BaseModel):
    """Strict input contract for summarization.
    
    Architectural Guarantee (TDR-010, FR-021):
    Contains ONLY verified sanitized text with placeholders (e.g. [PERSON], [EMAIL]).
    Contains NO raw unredacted text, original filenames, original PDF objects,
    raw candidate values, or coordinate mappings.
    """
    document_id: str = Field(description="Opaque session identifier (never original filename).")
    sanitized_text: str = Field(description="Verified redacted text containing only category/generic placeholders.")
    export_verification_ref: str = Field(description="Reference ID or timestamp of passing P5 export verification.")
    document_format: str = Field(default="txt", description="Document format ('txt' or 'pdf').")
    permitted_metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Safe metadata only (e.g. page count, char length). NEVER personal names or PII."
    )


class StructuredSummaryContent(BaseModel):
    """Structured content extracted or generated by summarization engine.
    
    Guarantees:
    - Structured key points and important findings.
    - Dates or figures restricted strictly to those present in sanitized source text.
    - Source evidence citing sanitized text sections.
    """
    summary_text: str = Field(description="Primary coherent paragraph summary of sanitized document.")
    key_points: List[str] = Field(default_factory=list, description="Key bullet points summarizing main topics.")
    important_findings: List[str] = Field(
        default_factory=list,
        description="Important conclusions, requirements, or contractual terms."
    )
    relevant_dates_or_figures: List[str] = Field(
        default_factory=list,
        description="Relevant dates or numeric figures present in sanitized text."
    )
    source_evidence: List[str] = Field(
        default_factory=list,
        description="Direct references or brief excerpts from sanitized text supporting the summary."
    )


class SummaryVerificationCheck(BaseModel):
    """Individual verification check performed by SummaryGuard."""
    check_name: str = Field(
        description="Check identifier (e.g. DIRECT_LEAKAGE, ALIAS_VARIANT, PII_REDETECTION, QUASI_IDENTIFIER, SOURCE_CONSISTENCY)."
    )
    status: str = Field(description="'PASSED', 'FAILED', or 'WARNING'.")
    details: str = Field(description="Masked diagnostic details. NEVER contains raw PII values.")


class QuasiIdentifierAssessment(BaseModel):
    """Assessment of quasi-identifier co-occurrence risk in summary text."""
    risk_level: QuasiRiskLevel = Field(default=QuasiRiskLevel.LOW, description="Assessed statistical risk level.")
    flagged_rules: List[str] = Field(default_factory=list, description="Identifiers of flagged quasi-identifier rules.")
    findings: List[str] = Field(default_factory=list, description="Masked descriptions of co-occurring attributes.")
    disclaimer: str = Field(
        default=(
            "Quasi-identifier risk evaluation assesses statistical re-identification risk flags based on "
            "demographic or contextual co-occurrences; it does not constitute mathematical or legal proof "
            "of complete anonymity."
        ),
        description="Mandatory disclaimer stating that quasi-identifier assessment does not prove complete anonymity."
    )


class SummaryVerificationReport(BaseModel):
    """Comprehensive privacy and consistency verification report for a generated summary."""
    status: str = Field(description="'PASSED', 'FAILED', or 'REQUIRES_REVIEW'.")
    checks: List[SummaryVerificationCheck] = Field(default_factory=list, description="Detailed check breakdown.")
    quasi_assessment: QuasiIdentifierAssessment = Field(
        default_factory=QuasiIdentifierAssessment,
        description="Quasi-identifier evaluation."
    )
    verified_at: str = Field(description="ISO timestamp of verification completion.")


class SummaryRequest(BaseModel):
    """Configuration payload for summarization request."""
    max_length: Optional[int] = Field(
        default=250,
        ge=50,
        le=1000,
        description="Approximate maximum word length for generated summary."
    )
    force_extractive: bool = Field(
        default=False,
        description="Explicitly request deterministic extractive fallback instead of local SLM."
    )


class SummaryResponse(BaseModel):
    """Complete API response for document summarization."""
    document_id: str = Field(description="Unique document session identifier.")
    state: SummaryState = Field(description="Current summary lifecycle state.")
    engine_used: SummaryEngine = Field(description="Engine that produced the summary.")
    content: Optional[StructuredSummaryContent] = Field(
        default=None,
        description="Structured summary content. Null/suppressed if verification failed."
    )
    verification_report: Optional[SummaryVerificationReport] = Field(
        default=None,
        description="Privacy guard verification audit report."
    )
    retry_count: int = Field(default=0, description="Number of retry attempts executed.")
    warning_message: Optional[str] = Field(
        default=None,
        description="Human-readable explanation if summary was suppressed, failed, or requires review."
    )
